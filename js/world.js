export const WORLD_HEIGHT =
    WORLD_MAP.length;


// ============================================
// TILE TYPES
// ============================================

export const TILE = {

    EMPTY: ".",

    WALL: "#"
};


// ============================================
// GET TILE
// ============================================

export function getTile(x, y) {

    const mapX =
        Math.floor(x);

    const mapY =
        Math.floor(y);


    if (
        mapX < 0 ||
        mapX >= WORLD_WIDTH ||
        mapY < 0 ||
        mapY >= WORLD_HEIGHT
    ) {

        return TILE.WALL;
    }


    return WORLD_MAP[mapY][mapX];
}


// ============================================
// WALL CHECK
// ============================================

export function isWall(x, y) {

    return (
        getTile(x, y) === TILE.WALL
    );
}


