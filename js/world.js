// ============================================
// TILE TYPES
// ============================================

export const TILE = {
    EMPTY: ".",
    WALL: "#"
};


// ============================================
// CHECK WHETHER A CELL IS SOLID
// ============================================

export function isWall(x, y) {

    const mapX = Math.floor(x);
    const mapY = Math.floor(y);

    if (
        mapX < 0 ||
        mapX >= WORLD_WIDTH ||
        mapY < 0 ||
        mapY >= WORLD_HEIGHT
    ) {
        return true;
    }

    return WORLD_MAP[mapY][mapX] === TILE.WALL;
}


// ============================================
// GET TILE
// ============================================

export function getTile(x, y) {

    const mapX = Math.floor(x);
    const mapY = Math.floor(y);

    if (
        mapX < 0 ||
        mapX >= WORLD_WIDTH ||
        mapY < 0 ||
        mapY >= WORLD_HEIGHT
    ) {
        return TILE.WALL;
    }

    return WORLD_MAP[mapY][mapX];
}


